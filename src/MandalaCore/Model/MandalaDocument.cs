using System;
using System.Collections.ObjectModel;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace MandalaMaker.Model;

public sealed class MandalaDocument : ObservableObject
{
    public const string FileExtension = ".mandala";

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
    };

    /// <summary>Reads a design from .mandala JSON text.</summary>
    public static MandalaDocument FromJson(string json)
    {
        var doc = JsonSerializer.Deserialize<MandalaDocument>(json, JsonOptions)
                  ?? throw new FormatException("The file is empty.");
        // Designs generated by earlier versions named layers with the British spelling
        foreach (var layer in doc.Layers)
            if (layer.Name.Contains("Centre")) layer.Name = layer.Name.Replace("Centre", "Center");
        return doc;
    }

    /// <summary>The design as .mandala JSON text (the same format the desktop app saves).</summary>
    public string ToJson() => JsonSerializer.Serialize(this, JsonOptions);

    /// <summary>A fully independent copy (used for print-time adjustments that mustn't touch the open design).</summary>
    public MandalaDocument DeepClone() =>
        JsonSerializer.Deserialize<MandalaDocument>(JsonSerializer.Serialize(this, JsonOptions), JsonOptions)!;

    private double _diameterMm = 200;
    private string _backgroundColor = "#FFF8EE";
    private bool _cutBorder;

    public int FormatVersion { get; set; } = 1;

    /// <summary>Overall artboard size. This is also the SVG export size.</summary>
    public double DiameterMm { get => _diameterMm; set => Set(ref _diameterMm, value < 10 ? 10 : value); }

    public string BackgroundColor { get => _backgroundColor; set => Set(ref _backgroundColor, value); }

    /// <summary>Adds a red outer cut circle at the full diameter (for coasters and ornaments).</summary>
    public bool CutBorder { get => _cutBorder; set => Set(ref _cutBorder, value); }

    private bool _noFill;

    /// <summary>
    /// Draw every layer as outlines only, without changing each layer's own Filled setting.
    /// Applies to the preview, SVG and PNG. Laser modes still use each layer's real fill to merge shapes and hide covered lines.
    /// </summary>
    public bool NoFill { get => _noFill; set => Set(ref _noFill, value); }

    /// <summary>Whether this layer is drawn with a fill, given the document-wide No fill switch.</summary>
    public bool ShowsFill(Layer layer) => layer.Filled && !NoFill;

    /// <summary>
    /// The stroke to draw. With No fill on, a layer with no stroke would disappear,
    /// so it gets a thin outline in its stroke color instead.
    /// </summary>
    public (double Width, string Color) EffectiveStroke(Layer layer) =>
        NoFill && layer.Filled && layer.StrokeWidth <= 0 ? (0.4, layer.StrokeColor) : (layer.StrokeWidth, layer.StrokeColor);

    /// <summary>Detail lines (echoes, inner shapes, hatching) are drawn a little thinner than the main outline.</summary>
    public (double Width, string Color) DetailStroke(Layer layer)
    {
        var (w, c) = EffectiveStroke(layer);
        return (Math.Max(w, 0.3) * 0.7, c);
    }

    private bool _connectPieces;
    private double _bridgeWidthMm = 2;

    /// <summary>Silhouette laser modes: join loose pieces to the main body with bridges so it cuts as one piece.</summary>
    public bool ConnectPieces { get => _connectPieces; set => Set(ref _connectPieces, value); }

    /// <summary>Width of each bridge in mm.</summary>
    public double BridgeWidthMm { get => _bridgeWidthMm; set => Set(ref _bridgeWidthMm, value < 0.2 ? 0.2 : value); }

    private LaserMode _laserMode = LaserMode.VisibleLines;

    /// <summary>How "Laser SVG" export (and the laser preview) cleans up the outlines.</summary>
    public LaserMode LaserMode { get => _laserMode; set => Set(ref _laserMode, value); }

    /// <summary>Index 0 is the top layer (drawn last).</summary>
    public ObservableCollection<Layer> Layers { get; set; } = new();

    public static MandalaDocument CreateStarter()
    {
        var doc = new MandalaDocument();
        doc.Layers.Add(new Layer { Name = "Center", Shape = ShapeKind.Circle, Count = 1, Radius = 0, Length = 14, Width = 14, FillColor = "#E76F51" });
        doc.Layers.Add(new Layer { Name = "Petals", Shape = ShapeKind.Petal, Count = 8, Radius = 20, Length = 26, Width = 13, FillColor = "#F4A261" });
        doc.Layers.Add(new Layer { Name = "Outer petals", Shape = ShapeKind.Petal, Count = 8, Radius = 36, Length = 30, Width = 16, OffsetHalfStep = true, FillColor = "#2A9D8F" });
        doc.Layers.Add(new Layer { Name = "Border", Shape = ShapeKind.Ring, Count = 1, Radius = 56, Length = 0, Width = 0, Filled = false, StrokeWidth = 1 });
        return doc;
    }
}
